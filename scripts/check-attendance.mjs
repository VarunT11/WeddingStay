import {build} from 'esbuild';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
const dir=await mkdtemp(tmpdir()+'/wedding-attendance-');
try{
 const outfile=dir+'/domain.mjs';
 await build({stdin:{contents:"export * from './src/data';export * from './src/attendance';export * from './src/management';export * from './src/transfer';",resolveDir:process.cwd()},outfile,bundle:true,platform:'node',format:'esm'});
 const m=await import(pathToFileURL(outfile));
 const guest=id=>({id,name:id,members:[],headcount:null,category:'',contact:'',needsAccommodation:null,notes:''});
 let data=m.normalizeData({...m.emptyDataset(),guests:[guest('a'),guest('b')],events:[{id:'e',name:'Celebration',date:'2020-01-01',location:'',notes:''}],invitations:[{id:'i',eventId:'e',guestGroupId:'a',response:'Confirmed',confirmedHeadcount:8}]});
 assert.equal(m.eventLifecycle(data.events[0]),'Upcoming');
 const legacy=JSON.parse(JSON.stringify(data));delete legacy.attendance;delete legacy.events[0].lifecycle;
 assert.deepEqual(m.parseDataset(JSON.stringify(legacy)).attendance,[]);
 data=m.changeEventLifecycle(data,'e','Completed','owner');
 assert.equal(m.eventAttendanceSummary(data,'e').unreviewed,1);
 assert.equal(data.attendance.length,0);
 data=m.saveAttendance(data,'e','a',{status:'Attended',actualHeadcount:3,notes:'Partial family'},'owner');
 assert.equal(data.invitations[0].confirmedHeadcount,8);
 assert.equal(m.eventAttendanceSummary(data,'e').actual,3);
 data=m.addEventAttendee(data,'e',guest('b'),null,'owner');
 assert.equal(data.invitations.length,1);
 assert.equal(m.eventAttendanceSummary(data,'e').unknownCounts,1);
 assert.throws(()=>m.addEventAttendee(data,'e',guest('b'),2,'owner'));
 assert.throws(()=>m.saveAttendance(data,'e','a',{status:'Attended',actualHeadcount:0,notes:''},'owner'));
 assert.throws(()=>m.mergeGuestAttendance(data,'a','b'));
 const selected=data.attendance.find(row=>row.guestGroupId==='a');
 const merged=m.mergeGuestAttendance(data,'a','b',{e:{recordId:selected.id,actualHeadcount:4}});
 assert.equal(merged.length,1);assert.equal(merged[0].actualHeadcount,4);
 assert.throws(()=>m.deleteEvent(data,'e'));
 const newData=m.addEventAttendee(data,'e',guest('c'),2,'owner');
 assert.equal(newData.guests.length,3);assert.equal(newData.guests[2].headcount,null);
 assert.deepEqual(m.parseDataset(JSON.stringify(m.storedData(newData))).attendance,newData.attendance);
 assert.equal(m.selectedEventColumns(data.events,{preset:'active',ids:[],mode:'auto'}).length,0);
 assert.equal(m.selectedEventColumns(data.events,{preset:'completed',ids:[],mode:'auto'}).length,1);
 assert.equal(m.selectedEventColumns(data.events,{preset:'custom',ids:[],mode:'attendance'}).length,0);
 console.log('Attendance checks passed: legacy import, lifecycle, counts, extra attendees, merge resolution, deletion protection, backup and matrix selection.');
}finally{await rm(dir,{recursive:true,force:true});}
